using UnityEngine;

namespace Woodberry.Core.Input
{
    /// <summary>
    /// Единственная точка доступа геймплея к вводу.
    /// Реализация скрывает Input System, чтобы геймплей не зависел от пакета
    /// и не знал строковых имён экшенов.
    /// </summary>
    public interface IInputReader
    {
        /// <summary>Вектор движения в плоскости XY. Уже нормализован по длине.</summary>
        Vector2 Move { get; }

        /// <summary>true пока удерживается спринт.</summary>
        bool SprintHeld { get; }

        /// <summary>
        /// Намерение взаимодействия.
        ///
        /// **Ограничение, важное для потребителя:** это кадровая семантика
        /// (<c>WasPressedThisFrame</c>), а движение живёт в <c>FixedUpdate</c>.
        /// Читать его из физического тика нельзя — на два кадра прединста
        /// приходится несколько тиков, и нажатие потерялось бы. Потребитель
        /// обязан читать из <c>Update</c>, либо применить буфер намерений.
        /// Буфер будет добавлен вместе с первым взаимодействием (Stage 03):
        /// сейчас его не на что вешать, а невызываемый код — мёртвый.
        /// </summary>
        bool InteractPressed { get; }

        /// <summary>
        /// Включает геймплейные action maps. Парный вызов обязателен.
        /// Имена из ADR 0005: речь именно о геймплейном вводе, UI-ввод живёт
        /// своим модулем и сюда не относится.
        /// </summary>
        void EnableGameplayInput();

        /// <summary>Выключает геймплейные action maps. Парный вызов обязателен.</summary>
        void DisableGameplayInput();
    }
}
