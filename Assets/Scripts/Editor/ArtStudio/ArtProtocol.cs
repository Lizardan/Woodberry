namespace Woodberry.Editor.ArtStudio
{
    /// <summary>
    /// Версия протокола Unity ↔ драйвер. Она же защита от дрейфа контракта:
    /// окно объявляет, какую версию умеет, драйвер сообщает свою в событии
    /// <c>ready</c>. Расхождение — это баннер с инструкцией, а не молчаливая
    /// поломка «прогресса нет».
    ///
    /// Правила роста версии (полная версия контракта —
    /// <c>docs/specs/art-generation.md</c>):
    /// - минорная правка, старые события ещё читаются → версия не меняется;
    /// - новое обязательное поле в событии или команде → версия +1;
    /// - смена смысла существующего поля → версия +1 и миграция не нужна,
    ///   потому что <c>events.jsonl</c> одноразовый и начинается заново.
    /// </summary>
    public static class ArtProtocol
    {
        public const int Version = 1;
    }
}
